// Helper currency formatting (Indian Rupee formatting: e.g. ₹8.6L, ₹75,000, ₹1.25 Cr)
export function formatINR(val: number, compact: boolean = false): string {
  if (val === undefined || val === null || isNaN(val)) return '₹0';
  
  if (compact) {
    if (val >= 10000000) {
      return `₹${(val / 10000000).toFixed(val % 10000000 === 0 ? 0 : 2)}Cr`;
    }
    if (val >= 100000) {
      return `₹${(val / 100000).toFixed(val % 100000 === 0 ? 0 : 1)}L`;
    }
    if (val >= 1000) {
      return `₹${(val / 1000).toFixed(0)}k`;
    }
  }

  // Standard Indian numbering format (e.g. 1,80,000)
  return '₹' + val.toLocaleString('en-IN');
}
